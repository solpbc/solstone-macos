#!/usr/bin/env python3
"""Generate native resources from the pinned catalog compiler; check committed byte drift."""
import argparse
import hashlib
import json
from pathlib import Path
import plistlib
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent.parent

def write_json(file, value):
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(json.dumps(value, indent=2, ensure_ascii=False) + '\n')

def tracked_outputs():
    config = json.loads((ROOT / 'i18n/targets.json').read_text())
    paths = list((ROOT / 'i18n/generated').rglob('*'))
    for target in config['targets']:
        paths += list((ROOT / 'Sources' / target / 'Localization').rglob('*'))
        paths.append(ROOT / 'Sources' / target / 'MacStrings.generated.swift')
    return sorted(p for p in paths if p.is_file())

def snapshot():
    inputs = list((ROOT / 'i18n/catalog').rglob('*')) + [ROOT/'i18n/compiler.json', ROOT/'i18n/targets.json']
    inputs += [ROOT/'scripts/i18n.py']
    result = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
              for p in sorted(inputs + tracked_outputs()) if p.is_file()}
    config = json.loads((ROOT/'i18n/targets.json').read_text())
    for plist_path, mapping in [('Sources/solstone/Info.plist', config['info']),
                                ('Sources/solstone-safari-extension/Info.plist', config['extension_info'])]:
        plist = plistlib.loads((ROOT/plist_path).read_bytes())
        localized = {key: plist.get(key) for key in list(mapping) + ['CFBundleDevelopmentRegion', 'CFBundleLocalizations']}
        result[plist_path+'#localized-values'] = hashlib.sha256(json.dumps(localized, sort_keys=True).encode()).hexdigest()
    return result

def check():
    expected = json.loads((ROOT/'i18n/generated-lock.json').read_text())
    actual = snapshot()
    changed = sorted(k for k in expected.keys() | actual.keys() if expected.get(k) != actual.get(k))
    if changed:
        raise SystemExit('catalog/generated bytes changed; regenerate with the pinned compiler:\n' + '\n'.join(changed))
    print('catalog and native generated resources match the committed byte lock')

