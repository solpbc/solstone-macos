if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    parser.add_argument('--compiler')
    parser.add_argument('--channel',default='production',choices=['production','development'])
    options=parser.parse_args()
    if options.check:
        check()
    elif options.compiler:
        generate(str(Path(options.compiler).resolve()),options.channel)
    else:
        parser.error('--compiler PATH is required for regeneration')
